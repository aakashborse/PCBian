/** Convert text to polylines centred horizontally on `at` (baseline at at.y), `height` in mm. */
export function strokeText(text: string, at: Vec, height: number, mirror = false): Vec[][] {
  const s = height / 6;
  const advance = 5.5 * s;
  const chars = [...text.toUpperCase()];
  const total = chars.length * advance - 1.5 * s;
  const out: Vec[][] = [];
  chars.forEach((ch, i) => {
    const glyph = G[ch] ?? G["#"];
    const ox = -total / 2 + i * advance;
    for (const stroke of glyph) {
      const pts: Vec[] = [];
      for (let k = 0; k < stroke.length; k += 2) {
        const x = ox + stroke[k] * s;
        pts.push({ x: at.x + (mirror ? -x : x), y: at.y - height + stroke[k + 1] * s });
      }
      out.push(pts);
    }
  });
  return out;
}
